def plan(d):
    comp = tools.compile_plan()
    _, text = comp.compile_plan(d)
    w(d, "business-plan.md", text)
    w(d, "summary.md", "# Summary (demo)\n\nA demo plan compiled from the founder-skill example.")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("project", help="folder to create (its founder/ is written inside)")
    ap.add_argument("--upto", choices=steps.KEYS, default="plan")
    ap.add_argument("--live", action="store_true", help="write the panel answers slowly, to watch them arrive")
    a = ap.parse_args(argv)
    d = os.path.join(os.path.abspath(a.project), "founder")
    os.makedirs(d, exist_ok=True)
    run = {"board": lambda: board(d), "competitors": lambda: competitors(d), "consumer": lambda: consumer(d, a.live),
           "pricing": lambda: pricing(d), "offer": lambda: offer(d), "cfo": lambda: cfo(d),
           "marketing": lambda: simple(d, "marketing"), "brand": lambda: simple(d, "brand"),
           "ops": lambda: simple(d, "ops"), "launch": lambda: simple(d, "launch"), "plan": lambda: plan(d)}
    for key in steps.KEYS:
        run[key]()
        print("demo: %s" % key)
        if key == a.upto:
            break
    print("wrote %s. Open it with: python3 gui/serve.py --dir %s" % (d, os.path.dirname(d)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
