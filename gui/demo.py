"""Build a demo founder/ folder from the matcha café example, to try the GUI without running the skills.

    python3 gui/demo.py /tmp/moss-demo                 # every step, as if the whole pack had run
    python3 gui/demo.py /tmp/moss-demo --upto consumer # stop after a step (board, competitors, consumer, ...)
    python3 gui/demo.py /tmp/moss-demo --live          # deal the panel and drip answers in, to watch it live

Everything it writes is marked as a demo. The buyer answers are generated by a
seeded random rule, NOT by buyer agents: they exist only so there is something
to look at. Never use them as a result.
"""

