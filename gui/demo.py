def consumer(d, live=False):
    panel = tools.panel()
    shutil.copy(os.path.join(SK, "founder-consumer", "customer.example.json"), os.path.join(d, "customer.json"))
    shutil.copy(os.path.join(SK, "founder-consumer", "pitch.example.md"), os.path.join(d, "pitch.md"))
    pdir = os.path.join(d, "panel")
    cards = panel.init(pdir, os.path.join(d, "customer.json"), os.path.join(d, "pitch.md"), 100, 7)
    panel.write_briefs(pdir)
    for c in cards:
        with open(os.path.join(pdir, "answers", c["id"] + ".json"), "w", encoding="utf-8") as fh:
            json.dump(answer(c), fh, indent=2)
        if live:
            time.sleep(0.35)
    res = panel.tally(pdir)
    w(pdir, "results.md", panel.results_md(res))
    with open(os.path.join(pdir, "results.json"), "w", encoding="utf-8") as fh:
        json.dump(res, fh, indent=2)


def pricing(d):
    vw = tools.pricing()
    rows, dropped = vw.read(os.path.join(d, "panel", "answers"))
    res = vw.analyse(rows)
